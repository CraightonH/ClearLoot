local A={}
local base=os.getenv("LOOTGOBLIN_ADDON") or "LootGoblin"
assert(loadfile(base.."/Model.lua"))("LootGoblin",A)
local total=0
local function test(name,fn) fn(); total=total+1; print("PASS "..name) end
local function new(id,link,time) return A.NewRoll(id,link or "item:a",time or 10,60,time or 10) end
local function drop(link,key,start)
    return {encounterID=7,lootListKey=key or 2,itemHyperlink=link or "item:a",startTime=start or 10}
end
test("need beats greed despite a lower number; server chooses winner",function()
    local r=new(1)
    A.ApplyDrop(r,{rollInfos={{playerName="You",isSelf=true,state=3,roll=99},
        {playerName="Tank",state=0,roll=2,isWinner=true}}},40)
    assert(r.status=="You lost" and r.winner.playerName=="Tank")
    local rows=A.SortedRows(r,A.InitDB({})); assert(rows[1].playerName=="Tank")
end)
test("waiting is not a loss, leader is not a winner",function()
    local r=new(1)
    A.ApplyDrop(r,{currentLeader={playerName="Tank"},rollInfos={{isSelf=true,state=0,roll=50},{state=4}}},40)
    assert(not r.finished and r.waiting==1 and r.status=="Rolling")
end)
test("all decisions made can still be resolving",function()
    local r=new(1); A.ApplyDrop(r,{rollInfos={{isSelf=true,state=0,roll=100}}},40)
    assert(r.status=="Resolving" and not r.finished)
end)
test("win, pass and everyone passed are distinct",function()
    local r=new(1); A.ApplyDrop(r,{winner={isSelf=true,playerName="You",state=0,roll=25},rollInfos={}},40)
    assert(r.status=="You won")
    r=new(2); A.ApplyDrop(r,{rollInfos={{isSelf=true,state=5},{state=0,isWinner=true}}},40)
    assert(r.status=="You passed")
    r=new(3); A.ApplyDrop(r,{allPassed=true,rollInfos={{isSelf=true,state=5}}},40)
    assert(r.status=="Everyone passed")
end)
test("late authoritative outcome reopens unknown result and resets timer",function()
    local r=new(1); r.status="Outcome unconfirmed"; r.finished=40; r.dismissed=true
    A.ApplyDrop(r,{winner={isSelf=true},rollInfos={}},100)
    assert(r.status=="You won" and r.finished==100 and not r.dismissed)
    A.ApplyDrop(r,{winner={isSelf=true},rollInfos={}},110); assert(r.finished==100)
end)
test("unique different items match independently",function()
    local a,b=new(1),new(2,"item:b")
    A.Match({a,b},{drop(),drop("item:b",3)})
    assert(a.key=="7:2" and b.key=="7:3")
end)
test("two identical items do not match arbitrarily",function()
    local a,b=new(1),new(2)
    A.Match({a,b},{drop(),drop(nil,3)})
    assert(not a.key and not b.key and a.match:find("uncertain"))
end)
test("one history record cannot serve two identical rolls",function()
    local a,b=new(1),new(2); A.Match({a,b},{drop()})
    assert(not a.key and not b.key)
end)
test("stale item and missing history never produce results",function()
    local r=new(1); A.Match({r},{drop(nil,nil,-50)})
    assert(not r.key and not r.finished)
    A.Match({r},{}); assert(not r.finished)
end)
test("claimed keys cannot be reused; alternate API field works",function()
    local a,b=new(1),new(2); a.key="7:2"; A.Match({a,b},{drop()}); assert(not b.key)
    local d=drop(); d.lootListID=99; d.lootListKey=nil; A.Match({b},{d}); assert(b.key=="7:99")
end)
test("completion timeout begins after outcome and respects pin, hover, keep",function()
    local r=new(1); local db=A.InitDB({})
    assert(not A.ShouldClose(r,db,999,false)); r.finished=100
    assert(not A.ShouldClose(r,db,119,false)); assert(A.ShouldClose(r,db,120,false))
    r.pinned=true; assert(not A.ShouldClose(r,db,999,false)); r.pinned=false
    assert(not A.ShouldClose(r,db,119,true)); assert(not A.ShouldClose(r,db,125,false))
    assert(A.ShouldClose(r,db,139,false)); db.closeAfter=0; assert(not A.ShouldClose(r,db,999,false))
end)
test("saved settings validation rejects wrong types and clamps extremes",function()
    local db=A.InitDB({layout="bad",scale=-100,closeAfter="bad",width=100000,opacity=0/0})
    assert(db.layout=="stack" and db.scale==0.65 and db.closeAfter==20 and db.width==650 and db.opacity==0.96)
end)
test("completion counts all choices including hidden passes, never elapsed time",function()
    local r=new(1)
    r.rows={{state=0},{state=3},{state=5},{state=4},{state=nil}}
    local chosen,n,complete=A.Completion(r)
    assert(chosen==3 and n==5 and not complete)
    r.rows[4].state=5; r.rows[5].state=1
    chosen,n,complete=A.Completion(r)
    assert(chosen==5 and n==5 and complete)
    assert(#A.SortedRows(r,A.InitDB({showPassed=false}))==3)
    r.rows={}; chosen,n,complete=A.Completion(r); assert(n==0 and not complete)
end)
test("choice groups stay Need, Greed, Pass, Waiting regardless of winner",function()
    local r=new(1); r.rows={{state=5,playerName="P"},{state=4,playerName="W"},
        {state=3,roll=99,isWinner=true,playerName="G"},{state=0,roll=1,playerName="N"}}
    local rows=A.SortedRows(r,A.InitDB({}))
    assert(rows[1].state==0 and rows[2].state==3 and rows[3].state==5 and rows[4].state==4)
    assert(A.RollGroup(0)==A.RollGroup(1))
end)
print(total.." model scenarios passed")
